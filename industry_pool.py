def industry_of(code6, name=""):
    """返回 code(6位) 对应行业；池内缺失按名称关键词识别；绝不返回「综合」"""
    c = str(code6).zfill(6)
    v = _UNI.get(c)
    if v and v != "其他":
        return v
    if name:
        for kw, ind in NAME_KEY:
            if kw in str(name):
                return ind
    return v if v else "其他"
