"""把 opt7（R-buffett-opt4-0916）结果与三方案终判写入三份文档（保留原 EOL）。"""
import io
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def read_doc(p):
    raw = open(p, "rb").read()
    crlf = b"\r\n" in raw
    text = raw.decode("utf-8").replace("\r\n", "\n")
    return text, crlf


def write_doc(p, text, crlf):
    out = text.replace("\n", "\r\n") if crlf else text
    open(p, "wb").write(out.encode("utf-8"))


def patch(path, edits, append=None):
    p = os.path.join(HERE, path)
    text, crlf = read_doc(p)
    ok = []
    for old, new, tag in edits:
        assert old in text, f"{path} MISS {tag}"
        text = text.replace(old, new, 1)
        ok.append(tag)
    if append:
        assert append[0] in text, f"{path} MISS {append[0]}"
        text = text.rstrip("\n") + "\n\n" + append[1] + "\n"
        ok.append("append")
    write_doc(p, text, crlf)
    print(f"[{path}] patched: {ok}")


